def scenarios():
    """Multi-clue environment scenarios: combine three attributes that only one environment matches."""
    keys = ["energy", "grain", "sorting", "structures", "rocks"]
    labels = {"energy": "energy", "grain": "sediment", "sorting": "sorting", "structures": "structures", "rocks": "rocks"}
    for env in ENVS:
        for _ in range(40):
            avail = [k for k in keys if env.get(k) and env[k] != "n/a"]
            ks = RNG.sample(avail, min(len(avail), RNG.choice([2, 3, 3, 4])))
            if not any(k in ("structures", "rocks") for k in ks):
                continue
            match = [e for e in ENVS if all(e.get(k) == env.get(k) for k in ks)]
            if len(match) != 1:
                continue
            clue = "; ".join(f"{labels[k]}: {env[k]}" for k in ks)
            lead = RNG.choice(["A geologist describes an ancient deposit", "A core sample shows", "An outcrop reveals",
                               "A sedimentary unit has"])
            mcq("3i.v.5", f"{lead} - {clue}. Which depositional environment is it?", env["name"],
                [e["name"] for e in ENVS if e is not env], diff=3, tags=["scenario", "depositional environment"], source="authored",
                specimens=env.get("sp", []))
