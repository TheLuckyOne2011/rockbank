"""Mineral knowledge base for the Science Olympiad Rocks & Minerals list.

Every value here feeds generated questions, so keep it conservative: when a
property varies, give the range or the most diagnostic value, not an edge case.

Fields
  slug, name, cls        Dana-style chemical class
  sil                    silicate structure (silicates only)
  group                  mineral group on the official list (or None)
  formula                display formula;  calc = simple formula for wt% math
  system                 crystal system (cubic, tetragonal, orthorhombic,
                         monoclinic, triclinic, trigonal, hexagonal, amorphous)
  H = (lo, hi)  SG = (lo, hi)
  luster [..]  streak  colors [..]  dia (diaphaneity)
  cleave = (n directions, quality, description)   n=0 means none
  fracture  tenacity
  habits [..]            only habits from the rulebook list
  special {tag: text}    acid, fluor, magnetic, smell, taste, double, piezo,
                         radio, feel, other
  color_cause            what produces the colour
  env [..]               formation environments
  uses [..]  ore         element(s) it is an ore of
  varieties {name: note}
  polymorphs [..]  series (name, end-members, note)
  clue                   one-line distinctive ID clue
  level                  'regional' or 'state' (starred on the official list)
  etym                   name origin
"""

M = []


def mineral(**k):
    k.setdefault("group", None)
    k.setdefault("sil", None)
    k.setdefault("special", {})
    k.setdefault("varieties", {})
    k.setdefault("polymorphs", [])
    k.setdefault("series", None)
    k.setdefault("ore", [])
    k.setdefault("habits", [])
    k.setdefault("calc", None)
    k.setdefault("etym", None)
    k.setdefault("color_cause", None)
    k.setdefault("level", "regional")
    k.setdefault("twinning", None)
    k.setdefault("aka", [])
    M.append(k)


